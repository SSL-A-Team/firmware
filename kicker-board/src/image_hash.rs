use core::ptr::read_volatile;

include!(concat!(env!("OUT_DIR"), "/fw_image_hashes.rs"));

struct ImgHash {
    #[allow(dead_code)]
    img_hash_magic: [u8; 16], // Used to find this struct in binary
    img_hash: [u8; 16], // Hash is injected by the flashing device's build (see util/fw_image_build.rs)
}

/// Kicker image hash, saved in the kicker image itself and reported to the
/// control board. Filled in when the control board build embeds this image.
static mut KICKER_IMG_HASH: ImgHash = ImgHash {
    img_hash_magic: *b"KickrImgHashKick",
    img_hash: [0; 16],
};

/// Hash of the dribbler image embedded in this image, generated by build.rs.
pub fn get_dribbler_img_hash() -> [u8; 16] {
    DRIBBLER_IMG_HASH
}

pub fn get_kicker_img_hash() -> [u8; 16] {
    // Enforce a read from memory because the hash is injected after compilation
    unsafe {
        return read_volatile(&raw const KICKER_IMG_HASH.img_hash as *const [u8; 16]);
    }
}
