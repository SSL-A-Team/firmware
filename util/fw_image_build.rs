// Build-script helper shared by the control-board and kicker-board build.rs
// (pulled in with `include!`).
//
// Prepares peripheral firmware images that are embedded into this image and
// flashed onto other devices (motor controllers, kicker), so the image
// hashes are known at compile time and plain `cargo build` / `cargo run`
// produce a complete image without any post-build step.
//
// For each source image:
//   1. If the image contains its self-hash struct (16 byte magic followed by
//      a 16 byte hash field, see motor-controller/common/image_hash.h), the
//      hash field is zeroed so the hash is stable.
//   2. The image is hashed (MD5).
//   3. The hash is written into the self-hash field, and the patched copy is
//      written to OUT_DIR for `include_bytes!`. The device reports this value
//      back, and the flashing device compares it against the hash constant
//      generated from step 2 to decide whether to reflash.

const IMG_HASH_MAGIC_LEN: usize = 16;
const IMG_HASH_LEN: usize = 16;

/// Prepares the flat binary `src` for inclusion as `$OUT_DIR/<out_name>` and
/// returns its image hash. Returns `None` (with a build warning) if `src`
/// hasn't been built.
fn prepare_fw_image(
    src: &std::path::Path,
    out_name: &str,
    self_hash_magic: &[u8; IMG_HASH_MAGIC_LEN],
) -> Option<[u8; IMG_HASH_LEN]> {
    println!("cargo:rerun-if-changed={}", src.display());
    let Ok(image) = std::fs::read(src) else {
        warn_missing_fw_image(src, out_name);
        return None;
    };
    Some(embed_fw_image(image, src, out_name, self_hash_magic))
}

fn warn_missing_fw_image(src: &std::path::Path, out_name: &str) {
    println!(
        "cargo:warning=firmware image '{}' not found, build it first (e.g. with make). \
         Binaries that include '{}' will fail to compile.",
        src.display(),
        out_name
    );
}

/// Hashes the flat binary `image` (read from `src`) and writes it to
/// `$OUT_DIR/<out_name>` with its self-hash field filled in.
/// `self_hash_magic` locates the image's own hash field; images without it
/// are hashed and written unmodified.
fn embed_fw_image(
    mut image: Vec<u8>,
    src: &std::path::Path,
    out_name: &str,
    self_hash_magic: &[u8; IMG_HASH_MAGIC_LEN],
) -> [u8; IMG_HASH_LEN] {
    use md5::{Digest, Md5};

    let mut matches = image
        .windows(IMG_HASH_MAGIC_LEN)
        .enumerate()
        .filter(|(_, w)| *w == self_hash_magic)
        .map(|(i, _)| i);
    let hash_field = match (matches.next(), matches.next()) {
        (None, _) => None,
        (Some(i), None) => Some(i + IMG_HASH_MAGIC_LEN..i + IMG_HASH_MAGIC_LEN + IMG_HASH_LEN),
        (Some(_), Some(_)) => panic!(
            "image hash magic '{}' occurs more than once in '{}'",
            String::from_utf8_lossy(self_hash_magic),
            src.display()
        ),
    };

    if let Some(field) = &hash_field {
        image[field.clone()].fill(0);
    }
    let hash: [u8; IMG_HASH_LEN] = Md5::digest(&image).into();
    if let Some(field) = hash_field {
        image[field].copy_from_slice(&hash);
    }

    let out = std::path::Path::new(&std::env::var_os("OUT_DIR").unwrap()).join(out_name);
    // Only rewrite on change so include_bytes! consumers keep their mtimes.
    if std::fs::read(&out).ok().as_deref() != Some(image.as_slice()) {
        std::fs::write(&out, &image).unwrap();
    }

    hash
}

/// Writes `$OUT_DIR/<out_name>` with a `pub const <NAME>: [u8; 16]` per entry.
/// Missing images get an all-zero hash.
fn write_fw_image_hash_consts(out_name: &str, hashes: &[(&str, Option<[u8; IMG_HASH_LEN]>)]) {
    use std::fmt::Write as _;

    let mut src = String::from("// Generated by build.rs, do not edit.\n");
    for (name, hash) in hashes {
        let hash = hash.unwrap_or([0; IMG_HASH_LEN]);
        writeln!(src, "pub const {name}: [u8; {IMG_HASH_LEN}] = {hash:?};").unwrap();
    }
    let out = std::path::Path::new(&std::env::var_os("OUT_DIR").unwrap()).join(out_name);
    if std::fs::read_to_string(&out).ok().as_deref() != Some(src.as_str()) {
        std::fs::write(&out, src).unwrap();
    }
}
